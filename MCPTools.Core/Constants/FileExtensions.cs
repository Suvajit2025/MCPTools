namespace MCPTools.Core.Constants;

/// <summary>
/// Contains file extension constants used by MCPTools.
/// </summary>
public static class FileExtensions
{
    /// <summary>
    /// Represents the C# source file extension.
    /// </summary>
    public const string CSharp = ".cs";

    /// <summary>
    /// Represents the SQL file extension.
    /// </summary>
    public const string Sql = ".sql";

    /// <summary>
    /// Represents the JSON file extension.
    /// </summary>
    public const string Json = ".json";

    /// <summary>
    /// Represents the XML file extension.
    /// </summary>
    public const string Xml = ".xml";

    /// <summary>
    /// Represents the Markdown file extension.
    /// </summary>
    public const string Markdown = ".md";

    /// <summary>
    /// Represents the text file extension.
    /// </summary>
    public const string Text = ".txt";

    /// <summary>
    /// Represents the YAML file extension.
    /// </summary>
    public const string Yml = ".yml";

    /// <summary>
    /// Represents the YAML file extension.
    /// </summary>
    public const string Yaml = ".yaml";

    /// <summary>
    /// Represents the C# project file extension.
    /// </summary>
    public const string CSharpProject = ".csproj";

    /// <summary>
    /// Represents the Visual Studio solution file extension.
    /// </summary>
    public const string Solution = ".sln";

    /// <summary>
    /// Represents the configuration file extension.
    /// </summary>
    public const string Config = ".config";

    /// <summary>
    /// Represents the MSBuild props file extension.
    /// </summary>
    public const string Props = ".props";

    /// <summary>
    /// Represents the MSBuild targets file extension.
    /// </summary>
    public const string Targets = ".targets";
}
